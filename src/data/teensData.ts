// Helper to get exactly 15 unique products for any requested category tab
export function getProductsForCategory(category: TeenCategory | string): TeenProduct[] {
  const norm = category.toLowerCase().trim();
  if (norm.includes('summer')) return SUMMER_26_15;
  if (norm.includes('teen girl') || norm === 'girls' || norm === 'tg') return TEEN_GIRLS_15;
  if (norm.includes('teen boy') || norm === 'boys' || norm === 'tb') return TEEN_BOYS_15;
  if (norm.includes('kid girl') || norm === 'kg') return KID_GIRLS_15;
  if (norm.includes('kid boy') || norm === 'kb') return KID_BOYS_15;
  if (norm.includes('infant') || norm.includes('baby')) return INFANT_15;
  if (norm.includes('trend')) return TRENDING_15;
  if (norm.includes('sale')) return SALE_15;
  return CATEGORY_PRODUCTS_MAP[category] || SUMMER_26_15;
}

