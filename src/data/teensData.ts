import { Product } from '../types';

export type TeenCategory =
  | "Summer '26"
  | 'Teen Girls'
  | 'Teen Boys'
  | 'Kid Girls'
  | 'Kid Boys'
  | 'Infant'
  | 'Trending'
  | 'Sale';

export interface HeroConfig {
  heading: string;
  subtitle: string;
  buttonText: string;
  buttonLink: string;
  imageUrl: string;
  mobileImageUrl?: string;
  overlayOpacity: number;
}

export interface TeenProduct {
  id: string;
  name: string;
  price: number;
  originalPrice?: number;
  category: 'Teen Girls' | 'Teen Boys' | 'Kid Girls' | 'Kid Boys' | 'Infant';
  tags?: string[];
  sizes: string[];
  inStock: boolean;
  badge?: 'New Arrival' | 'Best Seller' | 'Summer 26' | 'Limited' | 'Sale';
  imageUrl: string;
  hoverImageUrl?: string;
  sku: string;
  fabric: string;
  description: string;
  isFeatured?: boolean;
}

export function adaptTeenToProduct(p: TeenProduct): Product {
  return {
    id: p.id,
    name: p.name,
    price: p.price,
    originalPrice: p.originalPrice,
    categoryKey: 'coord',
    colorPalette: '#222222,#ffffff',
    tab: 'new',
    categorySlug: 'new',
    department: 'Teens',
    isNew: p.badge === 'New Arrival' || p.badge === 'Summer 26',
    fabric: p.fabric || 'Pure Cotton',
    details: p.description || '',
    sizes: p.sizes,
    sku: p.sku,
    imageUrl: p.imageUrl,
    images: [p.imageUrl, p.hoverImageUrl || p.imageUrl],
  };
}

